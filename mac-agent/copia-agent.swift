// Copia macOS agent: syncs the clipboard with a Copia server.
//
// Config: ~/.config/copia/copia.env
//   COPIA_TOKEN=...                       (required)
//   COPIA_SERVER=http://asgard:8787       (optional)
//   COPIA_DEVICE=my-mac                   (optional, defaults to the computer name)
//
// Build: swiftc -O -parse-as-library -o copia-agent copia-agent.swift

import AppKit
import CryptoKit
import Foundation
import UniformTypeIdentifiers

func logLine(_ msg: String) {
    print("\(ISO8601DateFormatter().string(from: Date())) \(msg)")
}

struct CopiaError: Error, CustomStringConvertible {
    let description: String
    init(_ description: String) { self.description = description }
}

struct Part: Decodable {
    let name: String?
    let mime: String
    let size: Int64
}

struct Item: Decodable {
    let id: String
    let kind: String
    let device: String?
    let size: Int64
    let hash: String
    let autoSync: Bool
    let preview: String?
    let parts: [Part]
}

struct Hello: Decodable {
    let latest: Item?
    let autoSyncLimit: Int64?
    let maxUpload: Int64?
}

struct Deleted: Decodable {
    let id: String
}

func sha256(_ data: Data) -> String {
    SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
}

func isValidID(_ s: String) -> Bool {
    s.range(of: "^[0-9a-f]{16}-[0-9a-f]{8}$", options: .regularExpression) != nil
}

struct Config {
    var token = ""
    var server = "http://asgard:8787"
    var device = ""
    var path = ""

    static func load() -> Config {
        var c = Config()
        let url = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent(".config/copia/copia.env")
        c.path = url.path
        if let text = try? String(contentsOf: url, encoding: .utf8) {
            for raw in text.split(whereSeparator: \.isNewline) {
                let line = raw.trimmingCharacters(in: .whitespaces)
                guard !line.hasPrefix("#"), let eq = line.firstIndex(of: "=") else { continue }
                let key = line[..<eq].trimmingCharacters(in: .whitespaces)
                let value = line[line.index(after: eq)...]
                    .trimmingCharacters(in: .whitespaces)
                    .trimmingCharacters(in: CharacterSet(charactersIn: "\"'"))
                switch key {
                case "COPIA_TOKEN": c.token = value
                case "COPIA_SERVER": if !value.isEmpty { c.server = value }
                case "COPIA_DEVICE": c.device = value
                default: break
                }
            }
        }
        while c.server.hasSuffix("/") { c.server.removeLast() }
        if c.device.isEmpty {
            // e.g. "Israel’s MacBook Pro" -> "Israels-MacBook-Pro" (HTTP headers must be plain ASCII)
            let raw = Host.current().localizedName ?? ProcessInfo.processInfo.hostName
            var name = ""
            for s in raw.unicodeScalars {
                if s.isASCII && CharacterSet.alphanumerics.contains(s) {
                    name.unicodeScalars.append(s)
                } else if s == " " || s == "-" || s == "_" {
                    name += "-"
                }
            }
            c.device = name.isEmpty ? "mac" : name
        }
        return c
    }
}

@MainActor
final class Agent {
    static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", // password managers (nspasteboard.org convention)
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    let cfg: Config
    let session: URLSession
    let eventsSession: URLSession
    let cacheDir: URL
    var autoSyncLimit: Int64 = 20 << 20
    var maxUpload: Int64 = 100 << 20
    var lastChangeCount: Int
    var ignoreChangeCount = -1 // pasteboard change we made ourselves
    var lastSig: String?       // what we last uploaded or applied
    var seen = Set<String>()

    init(cfg: Config) {
        self.cfg = cfg
        let c = URLSessionConfiguration.ephemeral
        c.timeoutIntervalForRequest = 60
        session = URLSession(configuration: c)
        let e = URLSessionConfiguration.ephemeral
        e.timeoutIntervalForRequest = 90 // the server pings every 25s
        e.timeoutIntervalForResource = 60 * 60 * 24 * 365
        eventsSession = URLSession(configuration: e)
        cacheDir = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("copia", isDirectory: true)
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func run() async {
        clearCache(keep: nil)
        logLine("copia agent started: server=\(cfg.server) device=\(cfg.device)")
        Task { await self.eventLoop() }
        while true {
            poll()
            try? await Task.sleep(nanoseconds: 500_000_000)
        }
    }

    // MARK: HTTP

    func request(_ method: String, _ path: String) -> URLRequest {
        var r = URLRequest(url: URL(string: cfg.server + path)!)
        r.httpMethod = method
        r.setValue("Bearer \(cfg.token)", forHTTPHeaderField: "Authorization")
        r.setValue(cfg.device, forHTTPHeaderField: "X-Copia-Device")
        return r
    }

    func check(_ data: Data, _ response: URLResponse) throws -> Data {
        let code = (response as? HTTPURLResponse)?.statusCode ?? 0
        guard (200..<300).contains(code) else {
            var detail = ""
            if let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
               let e = obj["error"] as? String {
                detail = ": \(e)"
            }
            throw CopiaError("HTTP \(code)\(detail)")
        }
        return data
    }

    func get(_ path: String) async throws -> Data {
        let (data, response) = try await session.data(for: request("GET", path))
        return try check(data, response)
    }

    func upload(_ body: Data, contentType: String) async throws {
        var r = request("POST", "/clip")
        r.setValue(contentType, forHTTPHeaderField: "Content-Type")
        let (data, response) = try await session.upload(for: r, from: body)
        _ = try check(data, response)
    }

    // MARK: live events

    func eventLoop() async {
        var backoff: UInt64 = 1
        var first = true
        while true {
            do {
                let (bytes, response) = try await eventsSession.bytes(for: request("GET", "/events"))
                let code = (response as? HTTPURLResponse)?.statusCode ?? 0
                guard code == 200 else { throw CopiaError("HTTP \(code)") }
                backoff = 1
                // `lines` drops blank lines, so dispatch on each data: line using the
                // event: line before it (the server sends exactly one of each per event).
                var event = "message"
                for try await line in bytes.lines {
                    if line.hasPrefix("event:") {
                        event = line.dropFirst(6).trimmingCharacters(in: .whitespaces)
                    } else if line.hasPrefix("data:") {
                        let payload = Data(line.dropFirst(5).trimmingCharacters(in: .whitespaces).utf8)
                        handle(event, payload, first: first)
                        if event == "hello" { first = false }
                        event = "message"
                    }
                }
                logLine("events: stream closed")
            } catch {
                logLine("events: \(error)")
            }
            try? await Task.sleep(nanoseconds: backoff * 1_000_000_000)
            backoff = min(backoff * 2, 30)
        }
    }

    func handle(_ event: String, _ data: Data, first: Bool) {
        let decoder = JSONDecoder()
        switch event {
        case "hello":
            guard let hello = try? decoder.decode(Hello.self, from: data) else { return }
            autoSyncLimit = hello.autoSyncLimit ?? autoSyncLimit
            maxUpload = hello.maxUpload ?? maxUpload
            logLine("connected to \(cfg.server)")
            if let latest = hello.latest {
                // Catch up on an item missed while offline, but don't overwrite the
                // clipboard when the agent first starts (e.g. at login).
                if !first && !seen.contains(latest.id) && latest.device != cfg.device {
                    receive(latest)
                }
                seen.insert(latest.id)
            }
        case "clip":
            guard let item = try? decoder.decode(Item.self, from: data) else { return }
            seen.insert(item.id)
            if item.device != cfg.device { receive(item) }
        case "delete":
            if let d = try? decoder.decode(Deleted.self, from: data), isValidID(d.id) {
                try? FileManager.default.removeItem(at: cacheDir.appendingPathComponent(d.id))
            }
        default:
            break
        }
    }

    func receive(_ item: Item) {
        guard item.autoSync else {
            logLine("not copied automatically: \(item.kind) from \(item.device ?? "?") is \(item.size) bytes (over the auto-sync limit)")
            return
        }
        Task {
            do {
                try await apply(item)
            } catch {
                logLine("apply \(item.id): \(error)")
            }
        }
    }

    // MARK: remote -> local clipboard

    func apply(_ item: Item) async throws {
        let pb = NSPasteboard.general
        switch item.kind {
        case "text":
            let data = try await get("/clip/\(item.id)/raw")
            let text = String(decoding: data, as: UTF8.self)
            pb.clearContents()
            pb.setString(text, forType: .string)
            markApplied("text:" + text)
            clearCache(keep: nil)
        case "image":
            var data = try await get("/clip/\(item.id)/raw")
            let mime = item.parts.first.map { String($0.mime.split(separator: ";").first ?? "") } ?? "image/png"
            if mime != "image/png", let rep = NSBitmapImageRep(data: data),
               let png = rep.representation(using: .png, properties: [:]) {
                data = png
            }
            pb.clearContents()
            pb.setData(data, forType: .png)
            markApplied("image:" + sha256(data))
            clearCache(keep: nil)
        default:
            // Files: download into ~/Library/Caches/copia/<id>/ and put file URLs on the pasteboard.
            let dir = cacheDir.appendingPathComponent(item.id, isDirectory: true)
            try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            var urls: [URL] = []
            var used = Set<String>()
            for (n, part) in item.parts.enumerated() {
                let data = try await get("/clip/\(item.id)/parts/\(n)")
                var name = (part.name ?? "")
                    .replacingOccurrences(of: "/", with: "_")
                    .replacingOccurrences(of: ":", with: "_")
                if name.isEmpty || name == "." || name == ".." { name = "item-\(n + 1)" }
                while used.contains(name) { name = "_" + name }
                used.insert(name)
                let url = dir.appendingPathComponent(name)
                try data.write(to: url)
                urls.append(url)
            }
            pb.clearContents()
            pb.writeObjects(urls.map { $0 as NSURL })
            markApplied("files:" + urls.map(\.path).joined(separator: "\n"))
            clearCache(keep: item.id)
        }
        logLine("received \(item.kind) from \(item.device ?? "?")")
    }

    func markApplied(_ sig: String) {
        lastSig = sig
        ignoreChangeCount = NSPasteboard.general.changeCount
        lastChangeCount = ignoreChangeCount
    }

    // Keep at most one received item's files on disk (the one on the clipboard now).
    func clearCache(keep: String?) {
        let fm = FileManager.default
        guard let names = try? fm.contentsOfDirectory(atPath: cacheDir.path) else { return }
        for name in names where name != keep {
            try? fm.removeItem(at: cacheDir.appendingPathComponent(name))
        }
    }

    // MARK: local clipboard -> server

    func poll() {
        let cc = NSPasteboard.general.changeCount
        guard cc != lastChangeCount else { return }
        lastChangeCount = cc
        guard cc != ignoreChangeCount else { return }
        Task {
            do {
                try await capture()
            } catch {
                logLine("upload: \(error)")
            }
        }
    }

    func capture() async throws {
        let pb = NSPasteboard.general
        let types = Set((pb.types ?? []).map(\.rawValue))
        if !types.isDisjoint(with: Agent.secretTypes) { return }

        // 1. Files copied in Finder.
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            try await uploadFiles(urls)
            return
        }

        // 2. Text (preferred over images when both are offered).
        if let text = pb.string(forType: .string), !text.isEmpty {
            let sig = "text:" + text
            guard sig != lastSig else { return }
            try await upload(Data(text.utf8), contentType: "text/plain; charset=utf-8")
            lastSig = sig
            logLine("sent text (\(text.utf8.count) bytes)")
            return
        }

        // 3. Image data (screenshots to clipboard, "Copy Image").
        var png = pb.data(forType: .png)
        if png == nil, let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
            png = rep.representation(using: .png, properties: [:])
        }
        if let png = png {
            let sig = "image:" + sha256(png)
            guard sig != lastSig else { return }
            guard Int64(png.count) <= min(autoSyncLimit, maxUpload) else {
                logLine("image not sent: \(png.count) bytes is over the auto-sync limit")
                return
            }
            try await upload(png, contentType: "image/png")
            lastSig = sig
            logLine("sent image (\(png.count) bytes)")
        }
    }

    func uploadFiles(_ urls: [URL]) async throws {
        let sig = "files:" + urls.map(\.path).joined(separator: "\n")
        guard sig != lastSig else { return }

        var total: Int64 = 0
        for url in urls {
            let values = try url.resourceValues(forKeys: [.isDirectoryKey, .fileSizeKey])
            if values.isDirectory == true {
                logLine("not sent: folders aren't synced yet (\(url.lastPathComponent))")
                return
            }
            total += Int64(values.fileSize ?? 0)
        }
        guard total <= maxUpload else {
            logLine("not sent: \(total) bytes is over the server's \(maxUpload)-byte limit")
            return
        }
        guard total <= autoSyncLimit else {
            logLine("not sent automatically: \(total) bytes is over the auto-sync limit")
            return
        }

        let boundary = "copia-\(UUID().uuidString)"
        var body = Data()
        func add(_ s: String) { body.append(Data(s.utf8)) }
        add("--\(boundary)\r\nContent-Disposition: form-data; name=\"kind\"\r\n\r\nfile\r\n")
        for url in urls {
            let name = url.lastPathComponent
                .replacingOccurrences(of: "\"", with: "'")
                .replacingOccurrences(of: "\r", with: "")
                .replacingOccurrences(of: "\n", with: "")
            let mime = UTType(filenameExtension: url.pathExtension)?.preferredMIMEType ?? "application/octet-stream"
            add("--\(boundary)\r\nContent-Disposition: form-data; name=\"file\"; filename=\"\(name)\"\r\nContent-Type: \(mime)\r\n\r\n")
            let contents = try Data(contentsOf: url)
            body.append(contents)
            add("\r\n")
        }
        add("--\(boundary)--\r\n")

        try await upload(body, contentType: "multipart/form-data; boundary=\(boundary)")
        lastSig = sig
        logLine("sent \(urls.count) file(s), \(total) bytes")
    }
}

@main
enum CopiaAgentMain {
    @MainActor
    static func main() async {
        setvbuf(stdout, nil, _IOLBF, 0) // line-buffered, so the log file updates live
        let cfg = Config.load()
        guard !cfg.token.isEmpty else {
            logLine("no COPIA_TOKEN in \(cfg.path)")
            exit(1)
        }
        guard URL(string: cfg.server) != nil else {
            logLine("invalid COPIA_SERVER: \(cfg.server)")
            exit(1)
        }
        await Agent(cfg: cfg).run()
    }
}
